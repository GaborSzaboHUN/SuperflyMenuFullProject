require('dotenv').config();
const express = require('express');
const cors = require('cors');
const fs = require('fs');
const path = require('path');
const { OAuth2Client } = require('google-auth-library');

const app = express();
const PORT = process.env.PORT || 5000;
const DATA_FILE = path.join(__dirname, 'data.json');

const googleClient = new OAuth2Client(process.env.GOOGLE_CLIENT_ID);

// .env:   ADMIN_EMAILS=first@gmail.com,second@gmail.com   (one string)
// result: ["first@gmail.com", "second@gmail.com"]          (a list)
const ADMIN_EMAILS = (process.env.ADMIN_EMAILS || '')
    .split(',')
    .map(email => email.trim());

app.use(cors());
app.use(express.json());



// - - - - - - HELPER FUNCTIONS TO READ AND WRITE DATA

const readData = () => JSON.parse(fs.readFileSync(DATA_FILE, 'utf8'));
const writeData = (data) => fs.writeFileSync(DATA_FILE, JSON.stringify(data, null, 4), 'utf8');



// - - - - - - AUTHENTICATION MIDDLEWARE

const authenticateAdmin = async (req, res, next) => {
    const authHeader = req.headers.authorization;

    if (!authHeader || !authHeader.startsWith('Bearer ')) {
        return res.status(401).json({ message: 'Unauthorized: Missing or invalid token format' });
    }

    const token = authHeader.split(' ')[1];

    try {
        const ticket = await googleClient.verifyIdToken({
            idToken: token,
            audience: process.env.GOOGLE_CLIENT_ID,
        });

        const payload = ticket.getPayload();

        // Check if the user email is on the admin list
        if (!ADMIN_EMAILS.includes(payload.email)) {
            return res.status(403).json({ message: 'Forbidden: You are not authorized as an admin' });
        }

        req.user = payload;
        next(); // Authorization successful, proceed to route handler
    } catch (error) {
        return res.status(401).json({ message: 'Unauthorized: Invalid token' });
    }
};



// - - - - - - PUBLIC ROUTES

// - - - - - - 1. READ (GET) - Fetch all menu items (Public)

app.get('/api/menu', (req, res) => {
    const menu = readData();
    res.json(menu);
});



// - - - - - - PROTECTED ADMIN ROUTES

// The menu structure is: { categories: [ { id, name, items: [ ... ] } ] }
// So every item route first needs to find the right category by its ID.

const findCategory = (menu, categoryId) =>
    menu.categories.find(category => category.id === categoryId);

// - - - - - - 2. CREATE (POST) - Add a new item to a category (Admin only)

app.post('/api/categories/:categoryId/items', authenticateAdmin, (req, res) => {
    const menu = readData();
    const category = findCategory(menu, req.params.categoryId);

    if (!category) {
        return res.status(404).json({ message: 'Category not found' });
    }

    // The ID is generated by the server, so it is always unique (e.g. "colds-1730971234567")
    const newItem = { ...req.body, id: `${category.id}-${Date.now()}` };
    category.items.push(newItem);
    writeData(menu);
    res.status(201).json(newItem);
});

// - - - - - - 3. UPDATE (PUT) - Update an existing item in a category (Admin only)

app.put('/api/categories/:categoryId/items/:itemId', authenticateAdmin, (req, res) => {
    const menu = readData();
    const category = findCategory(menu, req.params.categoryId);
    const item = category?.items.find(item => item.id === req.params.itemId);

    if (!item) {
        return res.status(404).json({ message: 'Item not found' });
    }

    // Overwrite the fields sent in the body, but never let the ID change
    Object.assign(item, req.body, { id: item.id });
    writeData(menu);
    res.json(item);
});

// - - - - - - 4. DELETE (DELETE) - Remove an item from a category (Admin only)

app.delete('/api/categories/:categoryId/items/:itemId', authenticateAdmin, (req, res) => {
    const menu = readData();
    const category = findCategory(menu, req.params.categoryId);
    const itemExists = category?.items.some(item => item.id === req.params.itemId);

    if (!itemExists) {
        return res.status(404).json({ message: 'Item not found' });
    }

    category.items = category.items.filter(item => item.id !== req.params.itemId);
    writeData(menu);
    res.json({ message: 'Deleted successfully!' });
});

app.listen(PORT, () => console.log(`Backend running on: http://localhost:${PORT}`));